"""Ticket store (SQLite): one row per ticket, plus human-in-the-loop review updates.

Ticket IDs come from the table's AUTOINCREMENT key (TKT-0001, ...), so they are unique across
threads and processes. Text is stored exactly as received; spreadsheet-formula neutralisation is
applied on EXPORT (export_frame), which is where it matters.
"""
from __future__ import annotations

from datetime import datetime
from pathlib import Path

import pandas as pd

import db
from guardrails.csv_safe import neutralise

COLUMNS = [
    "ticket_id", "timestamp", "owner", "customer_name", "order_id", "complaint",
    "category", "urgency", "sentiment", "language", "kb_sources", "citations",
    "response", "confidence", "status", "escalation_reason", "security_flags",
    "review_status", "final_response", "reviewed_by", "reviewed_at",
    "channel", "sender_email", "email_subject", "message_id", "caller_phone",
]
_INSERT_COLUMNS = [c for c in COLUMNS if c != "ticket_id"]  # ticket_id is generated by the database
_EXPORT_TEXT = [c for c in COLUMNS if c not in ("ticket_id", "timestamp", "confidence", "status")]
DECISIONS = ("Approved", "Edited", "Rejected")


def _confidence(value) -> float | None:
    try:
        f = float(value)
    except (TypeError, ValueError):
        return None
    return f if 0.0 <= f <= 1.0 else None


def _to_dict(row) -> dict:
    """Row as strings (what the UI and exports expect); NULL becomes an empty string."""
    out = {}
    for c in COLUMNS:
        v = row[c]
        out[c] = "" if v is None else (f"{v:.2f}" if c == "confidence" else str(v))
    return out


def append_ticket(row: dict, path: Path | None = None) -> dict:
    """Insert a ticket and return the stored row (including its generated ID and timestamp)."""
    status = row.get("status") or "Escalated"  # fail closed if a caller forgot the status
    values = {c: ("" if row.get(c) is None else str(row.get(c, ""))) for c in _INSERT_COLUMNS}
    values.update(
        timestamp=datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
        status=status,
        review_status=row.get("review_status") or ("Pending" if status == "Escalated" else "N/A"),
        confidence=_confidence(row.get("confidence")),
    )
    for c in ("category", "urgency", "sentiment"):
        values[c] = values[c] or "Unknown"
    values["channel"] = values["channel"] or "web"
    cols = ", ".join(_INSERT_COLUMNS)
    marks = ", ".join("?" for _ in _INSERT_COLUMNS)
    with db.transaction(path) as conn:
        cur = conn.execute(f"INSERT INTO tickets ({cols}) VALUES ({marks})", [values[c] for c in _INSERT_COLUMNS])
        stored = conn.execute(f"SELECT {', '.join(COLUMNS)} FROM tickets WHERE id = ?", (cur.lastrowid,)).fetchone()
    return _to_dict(stored)


def read_tickets(path: Path | None = None, owner: str | None = None, limit: int | None = None) -> pd.DataFrame:
    """Tickets oldest to newest as an all-string DataFrame.

    owner: only that owner's tickets, filtered inside the database (other users' rows are never loaded).
    limit: only the newest N tickets.
    """
    sql = f"SELECT {', '.join(COLUMNS)}, id FROM tickets"
    args: list = []
    if owner is not None:
        sql += " WHERE owner = ?"
        args.append(owner)
    sql += " ORDER BY id DESC"
    if limit:
        sql += " LIMIT ?"
        args.append(int(limit))
    rows = db.connect(path).execute(sql, args).fetchall()
    if not rows:
        return pd.DataFrame(columns=COLUMNS)
    return pd.DataFrame([_to_dict(r) for r in reversed(rows)], columns=COLUMNS)


def update_review(ticket_id: str, decision: str, final_response: str, reviewer: str, path: Path | None = None) -> bool:
    """HITL: record a human decision on a PENDING escalated ticket.

    Returns False if the ticket does not exist or was already reviewed, so two reviewers cannot
    silently overwrite each other.
    """
    if decision not in DECISIONS:
        raise ValueError("decision must be Approved, Edited or Rejected")
    with db.transaction(path) as conn:
        cur = conn.execute(
            "UPDATE tickets SET review_status = ?, final_response = ?, reviewed_by = ?, reviewed_at = ? "
            "WHERE ticket_id = ? AND status = 'Escalated' AND review_status = 'Pending'",
            (decision, final_response, reviewer, datetime.now().strftime("%Y-%m-%d %H:%M:%S"), ticket_id),
        )
        return cur.rowcount == 1


def export_frame(df: pd.DataFrame) -> pd.DataFrame:
    """A copy safe to hand to Excel/CSV: cells that could run as formulas are neutralised (CWE-1236)."""
    out = df.copy()
    for c in _EXPORT_TEXT:
        if c in out.columns:
            out[c] = out[c].map(neutralise)
    return out
